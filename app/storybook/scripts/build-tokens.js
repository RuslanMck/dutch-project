// Turns tokens/tokens.json into styles/tokens.css (CSS custom properties).
// Сад is light-only, so only the light value of each colour is written.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'));

const cssName = (name) => `--${name.replace(/\./g, '\\.')}`;
const lightOf = (value) => (typeof value === 'object' ? value.light : value);

const lines = [];
const section = (title, list) => {
  lines.push(`  /* ${title} */`);
  for (const t of list) lines.push(`  ${cssName(t.name)}: ${lightOf(t.value)};`);
};

section('colour', tokens.color.tokens);
lines.push('  /* type */');
for (const [name, stack] of Object.entries(tokens.type.families)) lines.push(`  --font-${name}: ${stack};`);
section('spacing', tokens.spacing.tokens);
section('radius', tokens.radius.tokens);
section('shadow', tokens.shadow.tokens);
section('size', tokens.size.tokens);

const css = `/* Generated by scripts/build-tokens.js from tokens/tokens.json — do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
writeFileSync(new URL('styles/tokens.css', root), css);
console.log(`tokens.css: ${lines.length} lines`);
