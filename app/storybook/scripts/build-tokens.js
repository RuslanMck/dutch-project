// Turns tokens/tokens.json into styles/tokens.css (CSS custom properties).
// Сад is light-only, so only the light value of each colour is written.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'));

const toCssName = (name) => `--${name.replace(/\./g, '\\.')}`;
const readLightValue = (value) => (typeof value === 'object' ? value.light : value);

const lines = [];
const writeSection = (title, tokenList) => {
  lines.push(`  /* ${title} */`);
  for (const token of tokenList) lines.push(`  ${toCssName(token.name)}: ${readLightValue(token.value)};`);
};

writeSection('colour', tokens.color.tokens);
lines.push('  /* type */');
for (const [name, stack] of Object.entries(tokens.type.families)) lines.push(`  --font-${name}: ${stack};`);
for (const [name, weight] of Object.entries(tokens.type.weights)) lines.push(`  --garden-weight-${name}: ${weight.value};`);
writeSection('spacing', tokens.spacing.tokens);
writeSection('radius', tokens.radius.tokens);
writeSection('shadow', tokens.shadow.tokens);
writeSection('size', tokens.size.tokens);

const css = `/* Generated by scripts/build-tokens.js from tokens/tokens.json — do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
writeFileSync(new URL('styles/tokens.css', root), css);
console.log(`tokens.css: ${lines.length} lines`);
